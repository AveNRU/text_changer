pub fn получить_замену(
    основной_словарь: &Text_Changer::Словари_с_кучами,
    слово_искомое: &String,
) -> Result<String, String> {
    //
    let mut слово_замена: Text_Changer::Умная_Строка =
        Text_Changer::Умная_Строка::Пусто;
    //
    if let Some(значения) = основной_словарь.кучи_полные.искомые[0]
        .простое
        .get(слово_искомое)
    {
        let указатель: usize = значения.iter().copied().next().unwrap();
        //
        слово_замена = Text_Changer::Умная_Строка::создать_значение(
            основной_словарь.сам.простое[указатель].замена.clone(),
        );
        // }
    };
    //
    match слово_замена {
        Text_Changer::Умная_Строка::Значение(_) => {
            return Ok(слово_замена.получить_значение());
        }
        Text_Changer::Умная_Строка::Пусто => {
            return Err(format!("Не нашлось замены для слова |{}|", слово_искомое));
        }
    }
}
