pub fn найти_не_переведённые_слова_в_основном_словаре(
    основной_словарь: &Text_Changer::Словари_с_кучами,
    данные_при_загрузке: &Данные_при_загрузке,
) -> Result<(), ()> {
    if данные_при_загрузке.не_загружать_основные_словари
    {
        return Ok(());
    }
    //
    let куча_не_добавленных_слов_из_главного_словаря_со_страницы_перевести: rapidhash::fast::RapidHashSet<usize> =
        основной_словарь.сам
            .перевести
            .par_iter()
            .enumerate() //.filter(|(указатель,ячейка)|!ячейка.искомое_слово.is_empty())
            .filter_map(|(указатель, ячейка)| {
                //если нет искомого слова из запасного словаря - то добавить его указатель в кучу
                //let ряд_знаков: Vec<char> = ячейка.искомое_слово.chars().collect();
                //если первый знак большой - вернуть отказ
                if !содержат_ли_слово_простые_кучи(
                    ячейка.искомое_слово.получить_ссылку_на_строку(),
                    &основной_словарь.кучи_простые.искомые,
                ) {
                    //если не содержит искомое слово кучи составные, составные важные и неимзенные коротки
                    if !содержат_ли_слово_3_кучи(
                        ячейка.искомое_слово.получить_ссылку_на_строку(),
                        &основной_словарь.кучи_простые.искомые,
                    ) {
                        Some(указатель)
                    } else {
                        None
                    }
                } else {
                    None
                }
            })
            .collect::<rapidhash::fast::RapidHashSet<usize>>();
    //
    //
    crate::output::write::вывод_основного_словаря_поискавшего(
        &куча_не_добавленных_слов_из_главного_словаря_со_страницы_перевести,
        &основной_словарь,
        //
    )
    .unwrap();

    Ok(())
}
