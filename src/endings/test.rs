pub fn поиск_недопустимых_окончаний_в_искомых_и_заменах(
    основной_словарь: &Text_Changer::Словари_с_кучами,
    вид_словаря: &Text_Changer::Вид_Словаря,
    данные_при_загрузке: &Данные_при_загрузке,
) -> Vec<String> {
    use crate::utils::stringzilla::sz_упорядочить_кучу_строк_rapid_в_ряд_строк;

    let время_отсчёта_недопустимых_окончаний: Instant = Instant::now();
    //
    println!(
        "{}",
        style(format!("\t Проверка недопустимых окончаний")).yellow(),
    );
    //
    let mut куча_недопустимых_окончаний_общий: rapidhash::fast::RapidHashSet<String> =
        rapidhash::fast::RapidHashSet::default();
    //
    for раздел in СТОПКА_ЛОЖНЫХ_ОКОНЧАНИЙ.iter() {
        //
        for образец in раздел.ряд_re.iter() {
            //
            let куча_исходных_слов: rapidhash::fast::RapidHashSet<String> =
                основной_словарь.кучи_полные.искомые[0]
                    .простое
                    .iter()
                    .filter_map(|слово_в_куче| {
                        //ссылка на исходное слово
                        let исходное_слово: &String = слово_в_куче.0;
                        //
                        //если есть совпадение исходного слова и RE образца
                        if образец.is_match(исходное_слово.as_str()) {
                            //
                            if есть_ли_слово_в_куче_исключений_ложных_окончаний(&исходное_слово,& раздел.ряд_исключений) {return None }
                             Some(исходное_слово.clone())
                        } else {None}
                    })
                    .collect::<rapidhash::fast::RapidHashSet<String>>();
            //
            куча_недопустимых_окончаний_общий.extend(куча_исходных_слов);
            //слова_замены
            let куча_слов_замен: rapidhash::fast::RapidHashSet<String> =
                основной_словарь.кучи_полные.искомые[0]
                    .простое
                    .iter()
                    .filter_map(|слово_в_куче| {
                        //ссылка на слово замену
                        let указатель_на_слово_замена:usize = получить_указатель_на_слово_замену_из_кучи(
                            &основной_словарь,
                            слово_в_куче,
                        )
                        .unwrap();
                        //получаем ссылку
                        let слово_замена:&String=основной_словарь.сам.простое[указатель_на_слово_замена].замена.получить_ссылку_на_строку();
                        //
                        //если есть совпадение  слова замены и RE образца
                        if образец.is_match(слово_замена.as_str()) {
                            //
                            if есть_ли_слово_в_куче_исключений_ложных_окончаний(&слово_замена,& раздел.ряд_исключений) {return None }
                             Some(слово_замена.clone())
                        } else {None}
                    })
                    .collect::<rapidhash::fast::RapidHashSet<String>>();
            //
            куча_недопустимых_окончаний_общий.extend(куча_слов_замен);
            //
        }
        //
    }
    let ряд_недопустимых_окончаний_общий =
        sz_упорядочить_кучу_строк_rapid_в_ряд_строк(
            куча_недопустимых_окончаний_общий,
        );
    //
    println!(
            "{}",
            style(format!(
                "⌚  Время занятое всего выполнения поиск недопустимых окончаний (от начала до конца): {:.2?}",
                время_отсчёта_недопустимых_окончаний.elapsed()
            ))
            .true_color(198, 100, 72)
        );
    return ряд_недопустимых_окончаний_общий;
}
pub fn есть_ли_пробелы_в_слове(слово: &String) -> bool {
    //let количество = слово.matches([' ', ' ']).count();
    // хорошо (увидит все виды пробелов):
    let количество = слово.chars().filter(|знак| знак.is_whitespace()).count();
    // let количество_черт_в_слове: usize = слово.matches(['-', '—', '–']).count();
    if количество > 0 {
        true
    } else {
        false
    }
}
//
pub fn есть_ли_слово_в_куче_исключений_ложных_окончаний(
    слово: &String,
    куча_исключений: &'static rapidhash::fast::RapidHashSet<&'static str>,
) -> bool {
    match есть_ли_пробелы_в_слове(слово) {
        true => {
            let раздел: Vec<&str> = слово.split_whitespace().collect();
            for выделенное_слово in раздел.iter() {
                //
                if куча_исключений.contains(выделенное_слово) {
                    return true;
                }
            }
        }
        //это одно слово
        false => {
            if куча_исключений.contains(слово.as_str()) {
                return true;
            }
        }
    }
    false
}
