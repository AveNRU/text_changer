pub fn проверка_окончания_re_и_слова_RE_Окончания_Поиск(
    ячейка: &RE_Окончания_Поиск,
) -> Result<(), rapidhash::fast::RapidHashSet<String>> {
    let mut куча: rapidhash::fast::RapidHashSet<String> = rapidhash::fast::RapidHashSet::default();
    if !sz_найти_в_str(ячейка.re_поиска.as_str(), &ячейка.вид_окончания.to_string())
    {
        куча.insert(format!(
            "0-В образце re поиска |{}| нет окончания |{}|",
            ячейка.re_поиска.as_str(),
            ячейка.окончание_строка
        ));
    }
    if !sz_найти_в_str(ячейка.re_замена.as_str(), &ячейка.вид_окончания.to_string())
    {
        куча.insert(format!(
            "1-В образце re замены |{}| нет окончания |{}|, байты: re замены |{:?}| окончания |{:?}|",
            ячейка.re_замена.as_str(),
            ячейка.окончание_строка,
             ячейка.re_замена.as_str().as_bytes(),
               ячейка.окончание_строка.as_bytes(),
        ));
    }
    if !sz_найти_в_str(&ячейка.вид_окончания.to_string(), &ячейка.окончание_строка)
    {
        куча.insert(format!(
            "2-В образце (окончание_строка) |{}| нет окончания |{}|, байты: окончание_строка |{:?}| окончания |{:?}|",
            &ячейка.re_поиска.to_string(),
            ячейка.окончание_строка,
            &ячейка.re_поиска.to_string().as_bytes(),
            ячейка.окончание_строка.as_bytes(),
        ));
    }
    //
    if !sz_найти_в_str(&ячейка.re_поиска.as_str(), ячейка.окончание_строка)
    {
        куча.insert(format!(
            "3-В образце re поиска |{}| нет |{}|",
            &ячейка.re_поиска.to_string(),
            ячейка.окончание_строка
        ));
    }
    if !sz_найти_в_str(&ячейка.re_замена.as_str(), ячейка.окончание_строка)
    {
        куча.insert(format!(
            "4-В образце re замены |{}| нет |{}|",
            &ячейка.re_замена.to_string(),
            ячейка.окончание_строка
        ));
    }
    if !ячейка
        .re_поиска
        .is_match(&format!("добавка{}", ячейка.окончание_строка))
    // if !sz_найти(&ячейка.re_образец.to_string(), ячейка.окончание_строка)
    {
        куча.insert(format!(
            "5-Образец RE поиска |{}| не сходится с  |{}|",
            &ячейка.re_поиска.to_string(),
            format!("добавка{}", ячейка.окончание_строка)
        ));
    }
    if !ячейка.re_замена.is_match(ячейка.окончание_строка)
    // if !sz_найти(&ячейка.re_образец.to_string(), ячейка.окончание_строка)
    {
        куча.insert(format!(
            "6-Образец RE замены |{}| не сходится с  |{}|",
            &ячейка.re_замена.to_string(),
            ячейка.окончание_строка
        ));
    }
    match куча.is_empty() {
        true => Ok(()),
        false => return Err(куча),
    }
}
