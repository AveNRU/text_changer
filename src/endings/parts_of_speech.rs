pub fn определено_ли_слову_часть_речи(
    слово: &str,
) -> Result<&'static [Вид_части_речи], ()> {
    //
    match СЛОВА_СУЩЕСТВИТЕЛЬНЫЕ_С_ЧАСТЯМИ_РЕЧИ.get(слово) {
        Some(успех) => Ok(*успех),
        None => Err(()),
    }
}
pub fn допустимый_раздел_для_слова(
    слово_нерусь: &String,
    части_речи_раздела: &RapidHashSet<Вид_части_речи>,
) -> bool {
    //является ли слово существительным
    match СЛОВА_СУЩЕСТВИТЕЛЬНЫЕ_С_ЧАСТЯМИ_РЕЧИ.contains_key(слово_нерусь.as_str())
    {
        //если существительное
        true => {
            return match части_речи_раздела.contains(&Вид_части_речи::Существительное)
            {
                //является ли раздел для существительных
                true => true,
                //если не существительное
                false => false,
            };
        }
        // не содержит слово искомое в куче существительных
        false => true,
    };
    //если слово не является существительным - то пропустить
    true
}
