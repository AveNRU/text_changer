pub fn добавить_слова_в_словарь(
    исходное_слово: String,                    //1-е слово (искомое)
    слово_замена: String,                      //2-е слово (замена)
    имя_страницы: Text_Changer::Имена_страниц, //номер страницы
    указатель_ячейки: u32,                     //номер ячейки
    путь_до_словаря: &String,
) -> Vec<Ячейка_словаря> {
    // let mut стопки_ячеек: Vec<Ячейка_словаря> = Vec::new(); //общий список для сравнения
    use crate::import::functions::*;
    //запрос на слово искомое в строке
    //вложение искомого слова
    if !исходное_слово.is_empty() && !слово_замена.is_empty() {
        //4 - неизменные
        //6 - неизменные короткие
        //7 - неизменные длинные
        //если это не неизменные слова
        if имя_страницы != Имена_страниц::Неизменные_стр
            && имя_страницы
                != Имена_страниц::Неизменные_короткие_стр
            && имя_страницы != Имена_страниц::Неизменные_длинные_стр
            && имя_страницы != Имена_страниц::Запятые
        {
            //с большой и маленькой буквой
            let исходные_слова: (String, String) =
                два_слова_из_одного_для_словаря(&исходное_слово);
            //с большой и маленькой буквой
            let слова_замены: (String, String) =
                два_слова_из_одного_для_словаря(&слово_замена);
            //возвращаем стопки
            //если не простое - то первая загланая и все остальные маленькие + все маленькие
            if имя_страницы != Имена_страниц::Простая_стр {
                return vec![
                    //для слова с большой буквой
                    Ячейка_словаря {
                        замена: слова_замены.0,
                        re_образец: получить_re_образец_по_слову(
                            &исходные_слова.0,
                            имя_страницы,
                        ),
                        искомое_слово: исходные_слова.0,
                    },
                    //для слова с маленькой буквой
                    Ячейка_словаря {
                        замена: слова_замены.1,
                        re_образец: получить_re_образец_по_слову(
                            &исходные_слова.1,
                            имя_страницы,
                        ),
                        искомое_слово: исходные_слова.1,
                    },
                ];
            }
            //если простые слова - то в слова где все буквы заглавные, все маленькие + 1-ая заглавная и остальные маленькие
            else {
                //с большой и маленькой буквой
                let исходные_слова: (String, String, String) =
                    три_слова_из_одного_для_словаря(&исходное_слово);
                //с большой и маленькой буквой
                let слова_замены: (String, String, String) =
                    три_слова_из_одного_для_словаря(&слово_замена);
                return vec![
                    //для слова с большой буквой
                    Ячейка_словаря {
                        замена: слова_замены.0,
                        re_образец: получить_re_образец_по_слову(
                            &исходные_слова.0,
                            имя_страницы,
                        ),
                        искомое_слово: исходные_слова.0,
                    },
                    //для слова с маленькой буквой
                    Ячейка_словаря {
                        замена: слова_замены.1,
                        re_образец: получить_re_образец_по_слову(
                            &исходные_слова.1,
                            имя_страницы,
                        ),
                        искомое_слово: исходные_слова.1,
                    },
                    //для слова где все большие буквы
                    Ячейка_словаря {
                        замена: слова_замены.2,
                        re_образец: получить_re_образец_по_слову(
                            &исходные_слова.2,
                            имя_страницы,
                        ),
                        искомое_слово: исходные_слова.2,
                    },
                ];
            }
        }
        //если неизменные слова - то выдирание как есть без смены строчных-заглавных букв
        else {
            return vec![Ячейка_словаря {
                замена: слово_замена,
                re_образец: получить_re_образец_по_слову(
                    &исходное_слово,
                    имя_страницы,
                ),
                искомое_слово: исходное_слово,
            }];
        }
    } else {
        if !слово_замена.is_empty() {
            println!(
                "Ячейка в словаре ({} страница) искомых слов пустая, её номер: {}, но ячейка со словом-заменой содержит не пустое значение: |{слово_замена}|. Путь до словаря {} ",
                имя_страницы,
                указатель_ячейки + 1,
                путь_до_словаря
            );
        }
        return Vec::new();
    }
}
