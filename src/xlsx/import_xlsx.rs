pub fn проверка_на_знаки_препинания(
    слово: &String,
) -> rapidhash::fast::RapidHashSet<String> {
    const ПЕРЕЧЕНЬ: [&'static str; 26] = [
        " ",  //0
        ".",  //1
        ":",  //2
        ",",  //3
        ";",  //4
        "`",  //5
        "?",  //6
        "!",  //7
        r"\", //8
        r"'", //9
        r"]", //11
        r"[", //12
        r"{", //13
        r"}", //14
        r"<", //15
        r">", //16
        r"=", //17
        r"&", //18
        r"^", //19
        r"%", //20
        r"$", //21
        r"*", //22
        r"(", //23
        r")", //24
        r"+", //25
        r"~", //26
    ];

    //проверка на неповторимость ряда
    static СЧЁТЧИК_ПРОВЕРКИ: AtomicBool = AtomicBool::new(false);
    //сама проверка
    if !СЧЁТЧИК_ПРОВЕРКИ.swap(true, Ordering::SeqCst) {
        crate::utils::functions_txt::есть_ли_повторно_строка_в_срезе_строк(&ПЕРЕЧЕНЬ.as_slice(), "знаки препинания",Раздел_Словаря::Не_является_разделом);
    }
    let куча_ошибок: rapidhash::fast::RapidHashSet<String> = ПЕРЕЧЕНЬ
        .into_par_iter()
        .enumerate()
        //.filter(|(число,образец)|!провера_пробела && *число==6)
        .filter_map(|(_число, образец)| {
            if sz_найти(слово, образец) {
                /* println!(
                    "{}",
                    format!(
                        "Простые слова: В Слове |{}| есть знак:|{}|  - что недопустимо",
                        слово, образец
                    )
                );*/
                Some(format!(
                    "Простые слова: В Слове |{}| есть знак:|{}|  - что недопустимо",
                    слово, образец
                ))
            } else {
                None
            }
        })
        .collect::<rapidhash::fast::RapidHashSet<String>>();
    return куча_ошибок;
}
