//поиск уже добавленных слов
pub fn поиск_уже_добавленных_слов(
    склад_всех_слов: &Vec<String>,     // для сравнения
    ряд_слов_исходных: &Vec<String>,   //куда образцы слов вкладываются
    ряд_слов_для_замены: &Vec<String>, //куда замены вставляются
    номер_стр: usize,                  //номер страницы
) {
    if номер_стр==0 {
        //поиск уже добавленных слов
        ряд_слов_исходных
            .par_iter().enumerate().for_each(|(i,слово)| {
            if sz_найти(&слово," ") {
                println!( "слово в словаре ({} стр): |{}| содержит пробел.",номер_стр,слово)
            }
        });
    }
    let mut куча:Mutex<HashSet<String>>= Mutex::new(HashSet::with_hasher(foldhash::fast::RandomState::default()));
    //поиск уже добавленных слов
    (0..склад_всех_слов.len())
        .into_par_iter()
        .for_each(|i| {
            ((i + 1)..склад_всех_слов.len())
                .into_par_iter()
                .for_each(|j| {
                    if склад_всех_слов[i] == склад_всех_слов[j] {
                        куча.lock().unwrap().insert(format!(
                            "слово в словаре ({} стр): |{}| уже добавлено. Номер строки 1){}, 2){}",
                            номер_стр, &склад_всех_слов[i], i, j
                        ));
                    }
                });
        });
    //поиск уже добавленных слов
    (0..ряд_слов_исходных.len())
        .into_par_iter()
        .for_each(|i| {
            ((i + 1)..ряд_слов_исходных.len())
                .into_par_iter()
                .for_each(|j| {
                    if ряд_слов_исходных[i] == ряд_слов_исходных[j] {
                        куча.lock().unwrap().insert(format!(
                            "слово в словаре ({} стр): |{}| уже добавлено. Номер строки 1){}, 2){}",
                            номер_стр, &ряд_слов_исходных[i], i, j
                        ));
                    }
                });
        });

    //проверка что количество слов равно
    if ряд_слов_исходных.len() != ряд_слов_для_замены.len() {
        println!(
            "Не равно количество слов ({} стр) искомых: {} и замен: {}",
            номер_стр,
            ряд_слов_исходных.len(),
            ряд_слов_для_замены.len()
        );
    }
    let mut куча = куча.into_inner().unwrap();
    for строка in куча.iter() {
        println!("{строка}");
    }
}

pub fn определение_имени_словаря(
    ряд_пути_до_словарей: &Vec<String>,
    i: usize,
) -> String {
    lazy_static! {
        pub static ref re_имя_словаря: Vec<Regex> = vec![
            Regex::new(r"(?i)\\([\d\w\s]+)\.(?:([\d\w_-]+))$").unwrap(),
            Regex::new(r"(?i)/([\d\w\s]+)\.(?:([\d\w_-]+))$").unwrap(),
        ];
    }
    let имя_словаря: String =
        re_имя_словаря.par_iter().find_map_any(|re_образец| {
            if let Some(caps) = re_образец.captures(&ряд_пути_до_словарей[i])
            {
                Some(caps[1].trim().to_string())
                //println!("refdes1");
            } else {None}
        }).unwrap_or_else(|| format!("Словарь_№_{}", i));
    return имя_словаря.to_string();

}
