pub fn найти_слова_которые_нет_в_куче_замены(
    куча_искомые: &rapidhash::fast::RapidHashSet<String>,
    куча_замены: &rapidhash::fast::RapidHashSet<String>,
) -> Vec<String> {
    use crate::utils::stringzilla::sz_упорядочить_кучу_строк_rapid_в_ряд_строк;
    let mut слова_которых_нет_в_куче_замены: rapidhash::fast::RapidHashSet<String> =
        rapidhash::fast::RapidHashSet::default();
    for слово in куча_искомые.iter() {
        if !куча_замены.contains(слово) {
            слова_которых_нет_в_куче_замены.insert(слово.clone());
        }
    }
    return sz_упорядочить_кучу_строк_rapid_в_ряд_строк(
        слова_которых_нет_в_куче_замены,
    );
}
