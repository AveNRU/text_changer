pub fn прочитать_xlsx_с_диска(
    путь: &str,
) -> Result<rapidhash::fast::RapidHashMap<String, Vec<Vec<String>>>, Box<dyn std::error::Error>> {
    let mut workbook: Xlsx<_> = match open_workbook(путь) {
        Ok(успех) => успех,
        Err(ошибка) => {
            println!(
                "Путь: {путь} не получислось открыть по причине: {}.\r\n Будет возвращён пустой .xlsx файл",
                ошибка
            );
            return Ok(rapidhash::fast::RapidHashMap::with_hasher(
                rapidhash::fast::RandomState::default(),
            ));
        }
    };
    let mut данные: rapidhash::fast::RapidHashMap<String, Vec<Vec<String>>> =
        rapidhash::fast::RapidHashMap::with_hasher(rapidhash::fast::RandomState::default());

    for имя_страницы in workbook.sheet_names().clone() {
        if let Ok(range) = workbook.worksheet_range(&имя_страницы) {
            let mut строки_листа = Vec::new();

            for row in range.rows() {
                let ячейки: Vec<String> = row
                    .iter()
                    .map(|cell| match cell {
                        Data::String(s) => s.clone(),
                        Data::Float(f) => f.to_string(),
                        Data::Int(i) => i.to_string(),
                        Data::Bool(b) => b.to_string(),
                        Data::DateTime(dt) => dt.to_string(),
                        Data::DateTimeIso(s) => s.clone(), // Добавлено
                        Data::DurationIso(s) => s.clone(), // Добавлено
                        Data::Empty => String::new(),
                        Data::Error(e) => format!("Ошибка: {:?}", e),
                    })
                    .collect();
                строки_листа.push(ячейки);
            }
            данные.insert(имя_страницы, строки_листа);
        }
    }
    Ok(данные)
}
// 3. Сравнение исходных и прочитанных данных
pub fn сравнить_данные(
    исходные: &rapidhash::fast::RapidHashMap<String, Vec<Vec<String>>>,
    прочитанные: &rapidhash::fast::RapidHashMap<String, Vec<Vec<String>>>,
) -> bool {
    if исходные.len() != прочитанные.len() {
        //   println!("❌ Разное количество листов: {} vs {}", исходные.len(), прочитанные.len());
        return false;
    }
    for (имя_листа, исходные_строки) in исходные {
        match прочитанные.get(имя_листа) {
            Some(прочитанные_строки) => {
                if исходные_строки != прочитанные_строки {
                    println!("❌ Лист '{}': данные различаются", имя_листа);
                    return false;
                }
            }
            None => {
                println!("❌ Лист '{}' отсутствует в прочитанных данных", имя_листа);
                return false;
            }
        }
    }
    //println!("✓ Данные идентичны!");
    true
}
