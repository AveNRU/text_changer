pub fn есть_ли_мусорные_расширения(строка: &String) -> bool {
    lazy_static! {
        static ref исключения: [String; 8] = [
            ".epub".to_string(),
            ".fb2".to_string(),
            ".htm".to_string(),
            ".fb3".to_string(),
            ".md".to_string(),
            ".fs".to_string(),
            ".yml".to_string(),
            ".mht".to_string(),
        ];
    }
    //счётчик - лишь 1 раз проверяет весь ряд
    static СЧЁТЧИК_ПРОВЕРКИ: AtomicBool = AtomicBool::new(false);
    //сама проверка
    if !СЧЁТЧИК_ПРОВЕРКИ.swap(true, Ordering::SeqCst) {
        crate::utils::functions_txt::есть_ли_повторно_строка_в_ряде(
            &исключения.as_ref(),
            "реклама после разбиения строк",
            lib::Раздел_Словаря::не_является_разделом,
        );
    };
    return исключения
        .par_iter()
        .any(|исключение| sz_найти(строка, исключение));
}

