pub fn вывод_словаря_переносов_всего(
    счётчики_замен: [Arc<Счётчик_замен>; 3],
    словарь_переносов: [Словарь_Переносов; 3],
) -> Result<(), String> {
    let (tx, rx) = mpsc::channel();
    //
    for (указатель_переносов, раздел_словаря) in словарь_переносов.into_iter().enumerate()
    {
        let счётчик: Arc<Счётчик_замен> = счётчики_замен[указатель_переносов].clone();
        let tx = tx.clone();
        rayon::spawn(move || {
            let время_выполнения: std::time::Duration =
                write::вывод_всех_счётчиков_замен_в_xlsx(
                    &счётчик,
                    &раздел_словаря,
                    указатель_переносов,
                )
                .unwrap();
            // Добавляем к сумме (в наносекундах)
            tx.send(время_выполнения).unwrap_or(());
        });
    }
    //
    let время2: std::time::Duration = rx.iter().sum();
    //
    println!(
        "{}",
        style(format!(
            "⌚\tВремя занятое на вывод словарей (переносы)  в .xlsx: {:.2?}",
            время2
        ))
        .true_color(154, 136, 252)
        .blink()
    );
    Ok(())
}
