//из utf8 в Windows 1251 для RTF
fn utf8_to_windows1251(utf8_срез: &str) -> Result<Vec<u8>, String> {
    let (итог, _, had_errors) = WINDOWS_1251.encode(utf8_срез);
    if had_errors {
        // Обработка символов, которые не могут быть представлены в Windows-1251
        eprintln!("Некоторые знаки не могут быть представлены в Windows-1251");
        return Err(format!(
            "Некоторые знаки не могут быть представлены в Windows-1251"
        ));
    }
    return Ok(итог.into_owned());
}
fn utf8_to_windows1252(utf8_срез: &str) -> Result<Vec<u8>, String> {
    let (итог, _, had_errors) = WINDOWS_1252.encode(utf8_срез);
    if had_errors {
        // Обработка символов, которые не могут быть представлены в Windows-1252
        eprintln!("Некоторые знаки не могут быть представлены в Windows-1252");
        return Err(format!(
            "Некоторые знаки не могут быть представлены в Windows-1252"
        ));
    }
    return Ok(итог.into_owned());
}
