pub fn считывание_книги_архивной(
    путь: &Text_Changer::Умная_Строка,
    расширение_полное: &Text_Changer::Расширение_полное,
    название_книги: &Text_Changer::Умная_Строка,
) -> Result<Text_Changer::Книга_с_сообщениями, ()> {
    //
    #[allow(non_camel_case_types)]
    struct Вложения_с_сообщениями {
        pub вложения: Vec<Text_Changer::Вложения>,
        pub сообщения: Text_Changer::Сообщения_считывания_книг,
    }

    use crate::utils::regex::re_получить_имя_файла_без_пути;

    let mut сообщения_файлов: Text_Changer::Сообщения_считывания_книг = Default::default();
    let mut содержимое_папок: Text_Changer::Содержимое_папок = Default::default();

    let книга_в_озу: Архив_в_озу = match zip_архив_в_память(
        путь,
        rapidhash::fast::RapidHashMap::with_hasher(rapidhash::fast::RandomState::default()),
    ) {
        Ok(успех) => успех,
        Err(ошибка) => {
            if sz_найти(&ошибка.to_string(), "Пустой файл") {
                вывод_сообщения_на_экран_и_вложение_в_кучу(
                    Text_Changer::Умная_Строка::создать_значение(
                        format!("☢️ Запись2:  книга {}. Пустое содержимое книги", путь),
                    ),
                    &mut сообщения_файлов.чтение_книг,
                );
                rapidhash::fast::RapidHashMap::with_hasher(rapidhash::fast::RandomState::default())
            } else {
                panic!("Ошибка при распаковке файла в архив |{путь}|")
            }
        }
    };

    // 1) Собираем в Vec<Вложения_с_сообщениями>
    let круговорот_книг_вектор: Vec<Вложения_с_сообщениями> = книга_в_озу
        .into_iter()
        .filter_map(|(имя_свитка_в_куче, содержимое_архива)| {
            let имя_свитка: Text_Changer::Умная_Строка =
                Text_Changer::Умная_Строка::создать_значение(
                    имя_свитка_в_куче,
                );
            let итог_расширения =
                получить_подробное_расширение(&имя_свитка);

            // картинки/шрифты — не читаем в utf8
            if !итог_расширения.вид.книга_ли() {
                let имя_без_пути =
                    re_получить_имя_файла_без_пути(&имя_свитка);
                проверка_на_непустоту_содержимого_при_считывании_нужны_байты(
                    &Vec::new(),
                    &содержимое_архива,
                    &имя_свитка,
                    &имя_без_пути,
                    &Text_Changer::Ошибка_Сохранения::Чтение_Диска,
                )
                .unwrap();

                Some(Вложения_с_сообщениями {
                    вложения: vec![Text_Changer::Вложения {
                        содержимое: Vec::new(),
                        имя_без_пути,
                        имя: имя_свитка,
                        путь_полный: путь.clone(),
                        содержимое_в_байтах: содержимое_архива.clone(),
                        кодировка:
                            Text_Changer::Кодировка::Не_определено,
                        расширение: Text_Changer::Расширение_полное {
                            строка: итог_расширения.строка,
                            вид: итог_расширения.вид,
                        },
                    }],
                    сообщения: Default::default(),
                })
            } else {
                let содержимое_файла: Vec<Text_Changer::Умная_Строка> =
                    read_utf8_из_ряда_u8(&содержимое_архива, &имя_свитка);

                if итог_расширения.вид.разметка_паутины()
                    || итог_расширения.вид.простая_письменность()
                {
                    let mut сообщения_свои: Text_Changer::Сообщения_считывания_книг =
                        Text_Changer::Сообщения_считывания_книг::default();
                    let новое_содержимое_файла: Vec<Text_Changer::Умная_Строка> =
                        htm_utf8_без_переносов_строк_в_умный_ряд(
                            &содержимое_файла,
                            &имя_свитка,
                            &расширение_полное.вид,
                        );
                    let кодировка: Text_Changer::Кодировка =
                        определить_кодировку(
                            &новое_содержимое_файла,
                            &имя_свитка,
                            &расширение_полное.вид,
                            путь,
                            &mut сообщения_свои.кодировка,
                        );

                    // ВАЖНО: не трогаем сообщения_файлов внутри замыкания.
                    let имя_без_пути =
                        re_получить_имя_файла_без_пути(&имя_свитка);
                    проверка_на_непустоту_содержимого_при_считывании_нужны_строки(
                        &новое_содержимое_файла,
                        &Vec::new(),
                        &имя_свитка,
                        &имя_без_пути,
                        &Text_Changer::Ошибка_Сохранения::Чтение_Диска,
                    )
                    .unwrap();

                    Some(Вложения_с_сообщениями {
                        вложения: vec![Text_Changer::Вложения {
                            содержимое: новое_содержимое_файла,
                            имя_без_пути,
                            имя: имя_свитка,
                            путь_полный: путь.clone(),
                            содержимое_в_байтах: содержимое_архива.clone(),
                            кодировка,
                            расширение: Text_Changer::Расширение_полное {
                                строка: итог_расширения.строка,
                                вид: итог_расширения.вид,
                            },
                        }],
                        сообщения: сообщения_свои,
                    })
                } else {
                    let mut сообщения_свои: Text_Changer::Сообщения_считывания_книг =
                        Text_Changer::Сообщения_считывания_книг::default();
                    let кодировка: Text_Changer::Кодировка =
                        определить_кодировку(
                            &содержимое_файла,
                            &имя_свитка,
                            &расширение_полное.вид,
                            путь,
                            &mut сообщения_свои.кодировка,
                        );

                    let имя_без_пути =
                        re_получить_имя_файла_без_пути(&имя_свитка);
                    проверка_на_непустоту_содержимого_при_считывании_нужны_строки(
                        &содержимое_файла,
                        &содержимое_архива,
                        &имя_свитка,
                        &имя_без_пути,
                        &Text_Changer::Ошибка_Сохранения::Чтение_Диска,
                    )
                    .unwrap();

                    Some(Вложения_с_сообщениями {
                        вложения: vec![Text_Changer::Вложения {
                            содержимое: содержимое_файла,
                            имя_без_пути,
                            имя: имя_свитка,
                            путь_полный: путь.clone(),
                            содержимое_в_байтах: содержимое_архива.clone(),
                            кодировка,
                            расширение: Text_Changer::Расширение_полное {
                                строка: итог_расширения.строка,
                                вид: итог_расширения.вид,
                            },
                        }],
                        сообщения: сообщения_свои,
                    })
                }
            }
        })
        .collect();

    // 2) Склеиваем Vec<Вложения_с_сообщениями> в один Вложения_с_сообщениями
    let круговорот_книг: Вложения_с_сообщениями = круговорот_книг_вектор.into_iter().fold(
        Вложения_с_сообщениями {
            вложения: Vec::new(),
            сообщения: Default::default(),
        },
        |mut итог, запчасть| {
            итог.вложения.extend(запчасть.вложения);
            // предполагаем, что у Сообщения_считывания_книг есть поле кодировка:
            итог
                .сообщения
                .кодировка
                .extend(запчасть.сообщения.кодировка);
            // и, если есть, чтение_книг:
            итог
                .сообщения
                .чтение_книг
                .extend(запчасть.сообщения.чтение_книг);
            итог
        },
    );

    содержимое_папок.файлы.insert(путь.получить_значение());

    /*let архив: rapidhash::fast::RapidHashMap<String, Vec<u8>> =
    rapidhash::fast::RapidHashMap::with_hasher(rapidhash::fast::RandomState::default());*/

    let книга_итог: Text_Changer::Книга_целиковая = Text_Changer::Книга_целиковая {
        вложения: круговорот_книг.вложения,
        архив: Default::default(),
        путь: путь.clone(),
        название_книги: название_книги.clone(),
        книга_ли: расширение_полное.вид.книга_ли(),
        расширение: расширение_полное.clone(),
    };

    // объединяем уже накопленные сообщения (ошибки распаковки) с сообщениями из файлов
    let mut итог_сообщений: Text_Changer::Сообщения_считывания_книг =
        сообщения_файлов;
    итог_сообщений
        .кодировка
        .extend(круговорот_книг.сообщения.кодировка);
    итог_сообщений
        .чтение_книг
        .extend(круговорот_книг.сообщения.чтение_книг);

    Ok(Text_Changer::Книга_с_сообщениями {
        книга: книга_итог,
        сообщения_файлов: итог_сообщений,
        содержимое_папок,
    })
}

