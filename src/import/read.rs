pub fn считать_книги(
    сообщения_приход: &mut Text_Changer::Сообщения_считывания_книг,
    данные_при_загрузке: &Данные_при_загрузке,
) -> Text_Changer::Книги_в_ОЗУ {
    use Text_Changer::{Вид_Книги, Основной_Вид_Расширения};
    // use crate::utils::functions::*;
    //use crate::utils::functions_add::прочитать_содержимое_построчно;
    //use crate::utils::read::*;
    use crate::utils::regex::определить_имя_книги;
    //use crate::utils::zip::{zip_архив_в_память, Архив_в_озу};
    use std::default::Default;
    //время, занятое на этот шаг
    let точка_отсчёта_по_времени: Instant = Instant::now();
    // Set the limit to 30000MiB.
    // ALLOCATOR.set_limit(30000 * 1024 * 1024).unwrap();
    //если не надо переводить
    if !данные_при_загрузке.включить_перевод {
        println!("Считывание книг отменено");
        return Default::default();
    }
    //
    let куча_нераспознанных_расширений: Arc<Mutex<rapidhash::fast::RapidHashSet<String>>> =
        Arc::new(Mutex::new(rapidhash::fast::RapidHashSet::default()));
    //вывод этапа
    println!(
        "{}",
        style(format!("\t[1/{ВСЕГО_ШАГОВ}]: Считывание книг")).yellow(),
    );

    //получение книг
    let пути_до_книг: Vec<Text_Changer::Умная_Строка> =
        получить_содержимое(&ПУТИ_ОБЩИЕ.книги);
    //получение словарей

    //получение книг
    let стопки_книг: Vec<Text_Changer::Книга_с_сообщениями> = пути_до_книг
        .par_iter()
        .enumerate()
        .filter_map(|(_i, путь)| {
            if sz_найти_в_умной_строке(&путь, r#"\"#) | sz_найти_в_умной_строке(&путь, r#"\\"#) {
                println!("путь с палкой: {путь}");
            };
            //открытие файла с библиотекой
            //расширение файла
            let mut расширение_строка: Text_Changer::Умная_Строка =
                match re_получить_строку_с_описанием(
                    &путь,
                    &RE_РАСШИРЕНИЕ_ФАЙЛА_C_ТОЧКОЙ,
                    "Не удалось выдрать расширение файла с точкой",
                ) {
                    Ok(путь) => путь,
                    Err(_) => Text_Changer::Умная_Строка::Пусто,
                    /*match re_получить_строку_с_описанием(
                                        &путь,
                                        &re_расширение_файла_без_точки,
                                        "Не удалось выдрать расширение файла без точки",
                                    ) {

                                        Ok(исход_2) => исход_2,
                                        Err(_) =>
                                            match re_получить_строку_с_описанием(
                                                &путь,
                                                &re_расширение_файла_3_й_случай,
                                                "Не удалось выдрать расширение файла 3-й случай",
                                            ) {
                                                Ok(исход_3)=>исход_3,
                                                Err(_) =>panic!("Не удалось извлечь расширение файла без точки и с точкой: {}", путь),
                                    }
                                    }
                    */
                };
            //
            let расширение_самой_книги_подробно: Text_Changer::Основной_Вид_Расширения = определить_расширение_подробно(
                &расширение_строка.to_lowercase());
                //&mut куча_нераспознанных_расширений.lock().unwrap());
            if расширение_строка.len() > 6 && !расширение_самой_книги_подробно.без_названия()
            {
                println!("Путь, где расширение больше 6 букв |{путь}|");
                println!("Расширение больше 6 букв |{расширение_строка}|");
                расширение_строка = Text_Changer::Умная_Строка::Пусто
            };
            let  расширение_полное: Text_Changer::Расширение_полное=Text_Changer::Расширение_полное{
                строка:расширение_строка.clone(),
                вид:расширение_самой_книги_подробно.clone(),
                };
            //имя файла
            let название_книги: Text_Changer::Умная_Строка = определить_имя_книги(путь);

            let книга_итог:Text_Changer::Книга_с_сообщениями=match  &расширение_самой_книги_подробно {
            Text_Changer::Основной_Вид_Расширения::Книга(содержимое) => {
                match содержимое {
                    Вид_Книги::Архивная(_) => считывание_книги_архивной(&путь,&расширение_полное,&название_книги).unwrap(),
                    Вид_Книги::Одиночная(_)=>считывание_книги_одиночной_решение(&путь,&расширение_полное,&название_книги).unwrap(),
                    //_=>Default::default(),
                }
            },
            Основной_Вид_Расширения::Разметка_Паутины(_)|Основной_Вид_Расширения::Мусорная_Разметка(_)|Основной_Вид_Расширения::XML(_)|Основной_Вид_Расширения::Реклама_html(_)=>
            считывание_файла_строк_htm_решение(&путь,&расширение_полное,&название_книги).unwrap(),
            //одиночный файл со строками

            |Основной_Вид_Расширения::JS(_)|Основной_Вид_Расширения::Простая_письменность(_)|Основной_Вид_Расширения::Приказы(_)|Основной_Вид_Расширения::Пусто|Основной_Вид_Расширения::Без_Названия

            =>считывание_файла_строк_построчно(&путь,&расширение_полное,&название_книги).unwrap(),
            _=>считывание_файла_как_путь(&путь,&расширение_полное,&название_книги).unwrap(),
            //
            };
            Some(книга_итог)
        })
        .collect();
    //
    let mut содержимое_папки: Text_Changer::Содержимое_папок =
        Text_Changer::Содержимое_папок::из_стопки_книг(&стопки_книг);
    let mut содержимое_файлов: Text_Changer::Сообщения_считывания_книг =
        Text_Changer::Сообщения_считывания_книг::из_стопки_книг(
            &стопки_книг,
        );
    //перебор содержимого книги на предмет наличия трех точек подряд
    crate::output::write::вывод_содержимого_папок_по_умолчанию(
        &mut содержимое_папки,
        "книги",
        &mut содержимое_файлов.общие,
        &данные_при_загрузке,
    )
    .unwrap();
    crate::output::dir::заменить_путь_выходным_книгам(
        &mut содержимое_папки.файлы,
        "книги",
    );

    содержимое_файлов
        .проверка_после_замен
        .extend(vec![Default::default(); стопки_книг.len()]);
    //println!("количество в стопке: {}",&сообщения.проверка_после_замен.len());
    *сообщения_приход = содержимое_файлов;
    //вывод этапа
    let количество_мегабайт: usize = (ALLOCATOR.allocated() / 1024) / 1024;
    println!(
        "{}{}",
        style(format!(
            "\tВыделено памяти на этапе [1/{ВСЕГО_ШАГОВ}]: Считывание книг:  "
        ))
        .bold(),
        style(format!("Мегабайт: {}", количество_мегабайт))
            .true_color(127, 255, 212)
            .bold(),
    );
    //вывод отчёта по времени, занятого на этот шаг
    println!(
        "{}",
        style(format!(
            "⌚  Время занятое на чтение книг: {:.2?}",
            точка_отсчёта_по_времени.elapsed()
        ))
        .true_color(154, 136, 252)
    );
    //
    let куча_нераспознанных_расширений: rapidhash::fast::RapidHashSet<String> =
        Arc::try_unwrap(куча_нераспознанных_расширений)
            .unwrap()
            .into_inner()
            .unwrap();
    //
    for расширение in куча_нераспознанных_расширений {
        println!("Не распознанное расширение: {}", расширение);
    }

    return Text_Changer::Книги_в_ОЗУ {
        книги: стопки_книг.into_iter().map(|ячейка| ячейка.книга).collect(),
        размер_в_озу: количество_мегабайт,
    };
}
