pub fn преобразовать_слово_с_чертой_в_начале(
    слово: String,
) -> String {
    let mut знаки: Vec<char> = слово.chars().collect();
    if let Some(знак) = знаки.get_mut(1) {
        *знак = знак.to_uppercase().next().unwrap_or(*знак);
    }
    знаки.iter().collect()
}
