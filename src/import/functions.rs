pub fn преобразовать_слово_с_чертой_в_конце_в_умную_строку(
    умная_строка: Text_Changer::Умная_Строка,
) -> Text_Changer::Умная_Строка {
    if умная_строка.не_пусто() {
        let значение = умная_строка.получить_значение();
        let mut знаки: Vec<char> = значение.chars().collect();

        if let Some(знак) = знаки.get_mut(0) {
            *знак = знак.to_uppercase().next().unwrap_or(*знак);
        }
        let итог: String = знаки.iter().collect();
        return Text_Changer::Умная_Строка::создать_значение(итог);
    } else {
        умная_строка // или Text_Changer::Умная_Строка::Пусто
    }
}

